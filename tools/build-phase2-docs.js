#!/usr/bin/env node
/* JFRESH OS — Phase 2 documentation generator (NP-01 … NP-06 + traceability)
   Reads the single source of truth (assets/js/jfos-config.js) and writes
   Markdown + CSV to docs/phase2/. No dependencies.
   Usage:  node tools/build-phase2-docs.js */
'use strict';
var fs = require('fs');
var path = require('path');

var ROOT = path.join(__dirname, '..');
var C = require(path.join(ROOT, 'assets/js/jfos-config.js'));
var OUT = path.join(ROOT, 'docs/phase2');
fs.mkdirSync(OUT, { recursive: true });

/* ---------- helpers ---------- */
// Indonesian first, English in parentheses when it differs
function P(p) { if (p == null) return '—'; if (!Array.isArray(p)) return String(p); return p[0] === p[1] ? p[0] : p[0] + ' (' + p[1] + ')'; }
function ID(p) { return Array.isArray(p) ? p[0] : String(p); }
function cell(s) { return String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\n/g, ' '); }
function table(head, rows) {
  return '| ' + head.map(cell).join(' | ') + ' |\n| ' + head.map(function () { return '---'; }).join(' | ') + ' |\n' +
    rows.map(function (r) { return '| ' + r.map(cell).join(' | ') + ' |'; }).join('\n') + '\n';
}
function roleName(k) { return ID(C.ROLES[k].n); }
function roles(list) { return list.map(roleName).join(', ') || '—'; }
function dom(k) { return C.SITEMAP.filter(function (d) { return d.k === k; })[0]; }
function prov(code) { return C.NB_PROVISIONAL.indexOf(code) !== -1 ? ' *(provisional)*' : ''; }
function nbList(codes, names) { return codes.map(function (c) { return c + (names ? ' ' + ID(C.NB[c]) : '') + prov(c); }).join(', '); }
function yes(b) { return b ? '✓' : '–'; }
function write(name, body) {
  var head = '<!-- Generated by tools/build-phase2-docs.js from assets/js/jfos-config.js (' + C.version + ', ' + C.date + '). Do not edit by hand. -->\n\n';
  fs.writeFileSync(path.join(OUT, name), head + body.replace(/\n{3,}/g, '\n\n'));
  console.log('wrote docs/phase2/' + name);
}
var ITEMS = C.SITEMAP.reduce(function (n, d) { return n + d.items.length; }, 0);
var PERMS = Object.keys(C.PERMS);

/* ---------- README ---------- */
var files = [
  ['np01-master-sitemap.md', 'NP-01', 'Master Sitemap', 'np01-sitemap.html'],
  ['np02-information-architecture.md', 'NP-02', 'Information Architecture', 'np02-information-architecture.html'],
  ['np03-role-navigation.md', 'NP-03', 'Navigasi Berdasarkan Peran (Role-Based Navigation)', 'np03-role-navigation.html'],
  ['np04-user-flows.md', 'NP-04', 'User Flow', 'np04-user-flows.html'],
  ['np05-screen-inventory.md', 'NP-05', 'Screen Inventory', 'np05-screen-inventory.html'],
  ['np06-screen-framework.md', 'NP-06', 'Functional Screen Framework', 'np06-screen-framework.html'],
  ['traceability-matrix.md', '—', 'Matriks Traceability (Traceability Matrix)', 'traceability.html'],
  ['traceability-matrix.csv', '—', 'Traceability Matrix (CSV)', 'traceability.html']
];
write('README.md',
  '# JFRESH OS — Fase 2: Struktur Sistem & Navigasi (Phase 2: System Structure & Navigation)\n\n' +
  '**' + C.version + '** · ' + C.date + ' · Simple Frontline — Powerful Management\n\n' +
  'These Markdown files are generated from `assets/js/jfos-config.js`, the same configuration that drives the working app (`app/`) and the HTML documentation pages (`phase2/`). Edit the configuration, never these files.\n\n' +
  '## Regenerate\n\n```sh\nnode tools/build-phase2-docs.js\n```\n\n' +
  '## Files\n\n' + table(['File', 'NP', 'Dokumen (Document)', 'HTML page'], files.map(function (f) { return ['[' + f[0] + '](' + f[0] + ')', f[1], f[2], '`phase2/' + f[3] + '`']; })) +
  '\n## Coverage\n\n' + table(['Item', 'Jumlah (Count)'], [
    ['Domain sitemap (Sitemap domains)', C.SITEMAP.length], ['Item sitemap (Sitemap items)', ITEMS], ['Layar (Screens)', C.SCREENS.length],
    ['Arsitipe layar (Screen archetypes)', Object.keys(C.ARCH).length], ['Peran (Roles)', C.ROLE_ORDER.length], ['Izin (Permissions)', PERMS.length],
    ['Alur utama (Main flows)', C.FLOWS.length], ['Field framework', C.FRAMEWORK_FIELDS.length]]) +
  '\n## Provisional NB codes\n\nOnly NB-04 (Receiving) and NB-05 (Reconciliation) come from the Phase 2 master prompt. ' +
  'The other NB codes follow the Phase 1 golden workflow and are marked *(provisional)* until the approved Navigation Brief list is attached: ' + C.NB_PROVISIONAL.join(', ') + '.\n');

/* ---------- NP-01 ---------- */
var s1 = '# NP-01 · Master Sitemap\n\n> **Sitemap = arsitektur global, bukan navigasi yang terlihat.** (The sitemap is global architecture only, not the visible navigation.) Each role sees only the menus its permissions allow — see NP-03.\n\n' +
  '**JFRESH OS — All-in-One Laundry Management System** · ' + C.SITEMAP.length + ' domains · ' + ITEMS + ' items · ' + C.SCREENS.length + ' screens\n\n';
C.SITEMAP.forEach(function (d) {
  var n = C.SCREENS.filter(function (s) { return s.dom === d.k; }).length;
  s1 += '## ' + d.n + '. ' + P(d.t) + '\n\n' + n + ' screens in this domain.\n\n' +
    table(['Item', 'Screen', 'Peran yang bisa membuka (Roles that can open it)'], d.items.map(function (it) { return [P(it.t), it.s + ' ' + ID(C.screen(it.s).n), roles(C.rolesFor(it.s))]; })) + '\n';
});
write('np01-master-sitemap.md', s1);

/* ---------- NP-02 ---------- */
var s2 = '# NP-02 · Information Architecture\n\nInformation is ordered by how often people need it: Level 1 is the most frequently accessed, Level 4 the least. Frequent actions are easier to reach than admin actions (Operator: Terima Cucian = 1 tap from home; Owner: Settings = Menu → Sistem → Pengaturan, hidden from every other role).\n\n## Levels\n\n' +
  table(['Level', 'Nama (Name)', 'Pertanyaan (Question)', 'Contoh (Examples)', 'Untuk siapa (For whom)', 'Layar (Screens)'], C.LEVELS.map(function (L) {
    return ['L' + L.n, P(L.t), P(L.q), L.ex.map(ID).join(', '), P(L.who), C.SCREENS.filter(function (s) { return s.lvl === L.n; }).length];
  })) +
  '\n## Role × level\n\n✓ = the role lives in that level (ROLES.levels). The number is how many screens of that level the role can open.\n\n' +
  table(['Peran (Role)'].concat(C.LEVELS.map(function (L) { return 'L' + L.n; })).concat(['Pertanyaan beranda (Home question)']), C.ROLE_ORDER.map(function (k) {
    var r = C.ROLES[k];
    return [roleName(k)].concat(C.LEVELS.map(function (L) {
      var n = C.SCREENS.filter(function (s) { return s.lvl === L.n && C.can(k, s.p); }).length;
      return (r.levels.indexOf(L.n) !== -1 ? '✓ ' : (n ? 'drill-down ' : '– ')) + (n || '');
    })).concat([P(r.q)]);
  })) + '\n## Screens per level\n\n';
C.LEVELS.forEach(function (L) { s2 += '- **L' + L.n + ' ' + P(L.t) + '**: ' + C.SCREENS.filter(function (s) { return s.lvl === L.n; }).map(function (s) { return s.id; }).join(', ') + '\n'; });
s2 += '\n## Alert priority\n\n' + table(['Level', 'Warna (Colour)', 'Contoh (Example)'], Object.keys(C.ALERTS).map(function (k) { var a = C.ALERTS[k]; return [P(a.t), a.color, P(a.ex)]; })) +
  '\n> **Jangan berlebihan memakai merah.** (Do not overuse red.) Red is only for late, failed, or needs action now. Most numbers stay blue; amber warns before it becomes red. Always icon + text, never colour alone.\n';
write('np02-information-architecture.md', s2);

/* ---------- NP-03 ---------- */
var s3 = '# NP-03 · Navigasi Berdasarkan Peran (Role-Based Navigation)\n\n## Permission rules\n\nA permission decides seven things: **menu, page, button, data, approval, edit, export**. ' +
  'Without permission the item is **hidden, not disabled**. The no-permission message (“' + ID(C.STATES.noperm.ex) + '”) only appears when someone opens a link they are not allowed to see. Clients only ever see their own data.\n\n';
C.ROLE_ORDER.forEach(function (k, i) {
  var r = C.ROLES[k];
  s3 += '## ' + (i + 1) + '. ' + P(r.n) + '\n\n- Perangkat utama (Primary device): ' + r.device + '\n- Pertanyaan beranda (Home question): “' + P(r.q) + '”\n- Rasa yang dituju (Intended feeling): “' + P(r.feel) + '”\n- Level IA: ' + r.levels.join(', ') + '\n- Beranda (Home): `' + r.nav[0].s + '` → app link `app/index.html#/' + k + '/' + r.nav[0].s + '`\n\n' +
    '**Menu PC & iPad**\n\n' + table(['Menu', 'Screen'], r.nav.concat(r.extra || []).map(function (n) { return [P(n.l), n.s]; })) +
    '\n**Navigasi bawah mobile (Mobile bottom nav, ' + r.mnav.length + '/5)**: ' + r.mnav.map(function (n) { return ID(n.l) + (n.s ? ' (`' + n.s + '`)' : ''); }).join(' · ') + '\n\n' +
    '**Tidak pernah melihat (Never sees)**: ' + r.hide.map(P).join(', ') + '\n\n';
});
s3 += '## Module visibility per role\n\nA module is visible when at least one of its screens is permitted. Number = screens.\n\n' +
  table(['Modul'].concat(C.ROLE_ORDER.map(roleName)), C.SITEMAP.map(function (d) {
    var ss = C.SCREENS.filter(function (s) { return s.dom === d.k; });
    return [d.n + '. ' + ID(d.t)].concat(C.ROLE_ORDER.map(function (k) { var n = ss.filter(function (s) { return C.can(k, s.p); }).length; return n ? '✓ ' + n : '–'; }));
  })) + '\n## Permission × role matrix (' + PERMS.length + ' permissions)\n\n' +
  table(['Izin (Permission)', 'Arti (Meaning)'].concat(C.ROLE_ORDER.map(roleName)), PERMS.map(function (p) {
    return ['`' + p + '`', P(C.PERMS[p])].concat(C.ROLE_ORDER.map(function (k) { return yes(C.can(k, p)); }));
  }));
write('np03-role-navigation.md', s3);

/* ---------- NP-04 ---------- */
var s4 = '# NP-04 · User Flow\n\nTap = counted interaction. Each step points at the screen that serves it.\n\n';
C.FLOWS.forEach(function (f, i) {
  var taps = f.steps.filter(function (s) { return s.tap && !s.bad; }).length;
  s4 += '## ' + (i + 1) + '. ' + f.code + ' ' + P(f.t) + '\n\n' + P(f.d) + '\n\n- Peran (Role): ' + roleName(f.role) + '\n- Target: ' + P(f.target) + ' · counted taps (main path): ' + taps + '\n- Coba alur ini (Try this flow): `app/index.html#/' + f.role + '/' + f.steps[0].s + '`\n\n' +
    table(['#', 'Langkah (Step)', 'Screen', 'Tap', 'Catatan (Note)'], f.steps.map(function (s, j) {
      return [j + 1, P(s.t), s.s, s.tap ? '✓' : '', [s.cta ? 'main button' : '', s.ok ? 'success' : '', s.bad ? 'issue branch' : '', s.opt ? 'optional' : '', s.next ? P(s.next) : ''].filter(Boolean).join(' · ')];
    })) + '\n';
});
s4 += '## Flow rules\n\n' + C.FLOW_RULES.map(function (r, i) { return (i + 1) + '. ' + P(r); }).join('\n') + '\n';
write('np04-user-flows.md', s4);

/* ---------- NP-05 ---------- */
var s5 = '# NP-05 · Screen Inventory\n\n> **Screen reuse rule.** Build a new screen from an existing archetype before inventing a layout. Receiving Queue (OPS-RCV-002) and QC Queue (OPS-QC-002) use the same Work Queue (T02) pattern.\n\n## Archetypes\n\n';
Object.keys(C.ARCH).forEach(function (a) {
  var A = C.ARCH[a], list = C.SCREENS.filter(function (s) { return s.a === a; });
  s5 += '### ' + a + ' · ' + P(A.n) + '\n\n' + P(A.d) + '\n\n- Dipakai untuk (Used for): ' + P(A.used) + '\n- Header: ' + P(A.header) + '\n- Area status: ' + P(A.statusArea) + '\n- Konten utama: ' + P(A.main) +
    '\n- Memuat (Loading): ' + P(A.loading) + '\n- Kosong (Empty): ' + P(A.empty) + '\n- PC: ' + P(A.responsive.d) + '\n- iPad: ' + P(A.responsive.t) + '\n- Mobile: ' + P(A.responsive.m) +
    '\n- Layar (' + list.length + '): ' + list.map(function (s) { return s.id; }).join(', ') + '\n\n';
});
s5 += '## Full screen inventory (' + C.SCREENS.length + ')\n\n' + table(['Screen ID', 'Nama (Name)', 'Arsitipe', 'Peran (Roles)', 'Level', 'Domain', 'Alur (Flow)'], C.SCREENS.map(function (s) {
  return [s.id, P(s.n), s.a + ' ' + ID(C.ARCH[s.a].n), roles(C.rolesFor(s)), 'L' + s.lvl, dom(s.dom).n + '. ' + ID(dom(s.dom).t), C.flowFor(s.id).map(function (f) { return f.code; }).join(', ') || '—'];
}));
write('np05-screen-inventory.md', s5);

/* ---------- NP-06 ---------- */
var STD = [['Header', 'Header'], ['Area Status', 'Status Area'], ['Konten Utama', 'Main Content'], ['Aksi Utama', 'Primary Action'], ['Aksi Sekunder', 'Secondary Action'], ['Panel Informasi', 'Information Panel'], ['Navigasi', 'Navigation'],
  ['State & Feedback', 'State & Feedback'], ['Izin', 'Permission'], ['Responsif', 'Responsive'], ['Audit & Log', 'Audit & Log'], ['Konsistensi', 'Consistency'], ['Bahasa', 'Language'], ['Aturan Bisnis', 'Business Rule']];
var s6 = '# NP-06 · Functional Screen Framework\n\n## Struktur standar setiap layar (Standard structure of every screen)\n\n' + STD.map(function (x, i) { return (i + 1) + '. ' + P(x); }).join('\n') +
  '\n\n## States\n\n' + table(['State', 'Teks default (Default copy)'], Object.keys(C.STATES).map(function (k) { return [P(C.STATES[k].t), P(C.STATES[k].ex)]; })) +
  '\n## Audit model\n\nAppend-only log. Every entry records: ' + C.AUDIT_FIELDS.map(P).join(', ') + '.\n\n' + table(['Event', 'Arti (Meaning)'], Object.keys(C.AUDIT).map(function (k) { return ['`' + k + '`', P(C.AUDIT[k])]; })) +
  '\n## Design tokens (assets/css/jfresh.css)\n\n' + table(['Token', 'PC ≥1240', 'iPad 700–1239', 'Mobile <700'], [
    ['Page title', '34 px', '28 px', '24 px'], ['Section title', '22 px', '20 px', '19 px'], ['Body', '16 px', '17 px', '16 px (min.)'], ['Small', '14 px', '14 px', '14 px'], ['KPI', '34 px', '30 px', '28 px'],
    ['Gutter', '32 px', '24 px', '16 px'], ['Card gap', '22 px', '18 px', '14 px'], ['Card padding', '22 px', '22 px', '22 px'], ['Radius', '22/16/12', '22/16/12', '18/16/12'], ['Icon', '20 / 24 / 28 px', '20 / 24 / 28 px', '20 / 24 / 28 px'],
    ['Button', '56 primary / 48 secondary', '56 / 48', '56 / 48, full width'], ['Touch target', '≥ 44 px (48)', '≥ 44 px (48)', '≥ 44 px (48)'], ['Chip', '13.5 px pill', '13.5 px', '13.5 px'], ['Table', '9×12 px cells, 14.5 px', 'compact 4–5 columns', 'cards']]) +
  '\n## Validation copy\n\nSay what is wrong and how to fix it, in everyday words, under the field. Write “Berat wajib diisi.”, never “weight_required_error”. No error codes, no ERP terms on frontline screens.\n\n' +
  '## Screen specifications (' + C.SCREENS.length + ' screens × ' + C.FRAMEWORK_FIELDS.length + ' fields)\n\n';
function fval(k, fw) {
  function lst(a, f) { return a && a.length ? a.map(f || P).join('; ') : '—'; }
  switch (k) {
    case 'id': return fw.id + ' · ' + fw.a + ' ' + ID(fw.arch) + ' · L' + fw.lvl;
    case 'roles': return roles(fw.roles);
    case 'pri': return fw.pri ? P(fw.pri) : '—';
    case 'sec': case 'f': case 'v': case 'r': case 'perm': return lst(fw[k]);
    case 'aud': return lst(fw.aud, function (a) { return '`' + a.k + '` ' + P(a.l); });
    case 'resp': return 'PC: ' + P(fw.resp.d) + ' · iPad: ' + P(fw.resp.t) + ' · Mobile: ' + P(fw.resp.m);
    case 'lang': return lst(fw.lang, function (p) { return p[0] + ' / ' + p[1]; });
    case 'map': return 'NB: ' + nbList(fw.nb, true) + ' · NV: ' + fw.nv.join(', ') + ' · BF: ' + fw.bf.join(', ') + (fw.flow.length ? ' · Flow: ' + fw.flow.join(', ') : '');
    default: return P(fw[k]);
  }
}
C.SITEMAP.forEach(function (d) {
  var ss = C.SCREENS.filter(function (s) { return s.dom === d.k; });
  if (!ss.length) return;
  s6 += '### ' + d.n + '. ' + P(d.t) + '\n\n';
  ss.forEach(function (s) {
    var fw = C.framework(s.id);
    s6 += '#### ' + s.id + ' — ' + P(s.n) + '\n\n' + table(['#', 'Field', 'Nilai (Value)'], C.FRAMEWORK_FIELDS.map(function (f, i) { return [i + 1, P(f[1]), fval(f[0], fw)]; })) +
      '\nLihat di aplikasi (View in app): `app/index.html#/' + fw.roles[0] + '/' + s.id + '`\n\n';
  });
});
write('np06-screen-framework.md', s6);

/* ---------- Traceability ---------- */
function trRow(s) {
  return [s.id, ID(s.n), roles(C.rolesFor(s)), s.bf.map(function (c) { return c + ' ' + ID(C.BF[c]); }).join('; '), nbList(s.nb, true), C.nvFor(s).join(', '), s.a + ' ' + ID(C.ARCH[s.a].n),
    C.flowFor(s.id).map(function (f) { return f.code; }).join(', ') || '—', s.p, s.pri ? s.pri[1] : '—'];
}
var TRH = ['Screen ID', 'Nama (Name)', 'Peran (Roles)', 'Fase 1 (BF)', 'NB', 'NV', 'Arsitipe', 'Alur (Flow)', 'Izin lihat (View perm.)', 'Izin aksi utama (Primary-action perm.)'];
var ordered = C.SCREENS.slice().sort(function (a, b) { return (b.id === 'OPS-RCV-001') - (a.id === 'OPS-RCV-001'); });
var st = '# Matriks Traceability (Traceability Matrix)\n\nHow to read a row — example from the brief: **OPS-RCV-001 Terima Cucian** → NB-04 Receiving, NB-05 Reconciliation → NV-03, NV-04, NV-05, NV-06. NV-01 (sitemap) applies to every screen and is implied. *(provisional)* marks NB codes awaiting the approved NB list.\n\n' +
  table(TRH, ordered.map(trRow)) + '\n## Reverse view: NB → screens\n\n' +
  table(['NB', 'Nama (Name)', 'Layar (Screens)'], Object.keys(C.NB).map(function (k) {
    var ss = C.SCREENS.filter(function (s) { return s.nb.indexOf(k) !== -1; });
    return [k + prov(k), P(C.NB[k]), ss.length ? ss.map(function (s) { return s.id; }).join(', ') : '**GAP: no screen**'];
  })) + '\n## Reverse view: Phase 1 (BF) → screens\n\n' +
  table(['BF', 'Nama (Name)', 'Layar (Screens)'], Object.keys(C.BF).map(function (k) {
    var ss = C.SCREENS.filter(function (s) { return s.bf.indexOf(k) !== -1; });
    return [k, P(C.BF[k]), ss.length ? ss.map(function (s) { return s.id; }).join(', ') : '**GAP: no screen**'];
  }));
write('traceability-matrix.md', st);

function csv(v) { v = String(v == null ? '' : v); return /[",\n]/.test(v) ? '"' + v.replace(/"/g, '""') + '"' : v; }
var csvH = ['screen_id', 'name_id', 'name_en', 'roles', 'bf', 'nb', 'nb_provisional', 'nv', 'archetype', 'flow', 'ia_level', 'domain', 'view_permission', 'primary_action_permission'];
var csvRows = C.SCREENS.map(function (s) {
  return [s.id, s.n[0], s.n[1], C.rolesFor(s).join(' '), s.bf.join(' '), s.nb.join(' '), s.nb.filter(function (c) { return C.NB_PROVISIONAL.indexOf(c) !== -1; }).join(' '), C.nvFor(s).join(' '),
    s.a, C.flowFor(s.id).map(function (f) { return f.code; }).join(' '), s.lvl, s.dom, s.p, s.pri ? s.pri[1] : ''];
});
fs.writeFileSync(path.join(OUT, 'traceability-matrix.csv'), '﻿' + [csvH].concat(csvRows).map(function (r) { return r.map(csv).join(','); }).join('\r\n') + '\r\n');
console.log('wrote docs/phase2/traceability-matrix.csv');
