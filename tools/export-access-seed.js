#!/usr/bin/env node
/* Generates the Supabase reference-data migration (plants, roles, permissions,
   role → permission grants) from the JS access engines, installed in the same
   order as the app. The engines stay the single source of truth for the role
   model; re-run this after a phase changes roles or permissions and commit the
   output as a NEW migration (never edit one that already ran in production).

   Usage: node tools/export-access-seed.js [output.sql]
   Default output: supabase/migrations/20261007160100_access_reference_data.sql */
global.window = undefined;
const fs = require('fs'), path = require('path');
const R = '../assets/js/';
const C = require(R + 'jfos-config.js'), X = require(R + 'jfos-access.js');
const P = require(R + 'jfos-perf.js'); P.install(C, X);
const CM = require(R + 'jfos-comm.js'); CM.install(C, X, P);
const LG = require(R + 'jfos-logi.js'); LG.install(C, X, P, CM);
const PR = require(R + 'jfos-prod.js'); PR.install(C, X, P, CM, LG);
const DL = require(R + 'jfos-dlv.js'); DL.install(C, X, P, CM, LG, PR);
const F = require(R + 'jfos-fin.js'); F.install(C, X, P, CM, LG, PR, DL);
const CLP = require(R + 'jfos-clp.js'); CLP.install(C, X, P, CM, LG, PR, DL, F);
const S = require(R + 'jfos-sys.js'); S.install(C, X, P, CM, LG, PR, DL, F, CLP);

const out = process.argv[2] || path.join(__dirname, '../supabase/migrations/20261007160100_access_reference_data.sql');
const q = v => v == null ? 'null' : "'" + String(v).replace(/'/g, "''") + "'";
const name = n => Array.isArray(n) ? n : [n, n];

const roleKeys = Object.keys(X.ROLES);
const grants = [];
const perms = new Set();
roleKeys.forEach(k => X.rolePerms(k).forEach(p => { perms.add(p); grants.push([k, p]); }));
Object.keys(C.ROLES).forEach(k => C.ROLES[k].perms.forEach(p => perms.add(p)));
X.USERS.forEach(u => (u.deny || []).forEach(p => perms.add(p)));
const permList = [...perms].sort();
const uniq = [...new Set(grants.map(g => g.join('\u0000')))].map(s => s.split('\u0000')).sort((a, b) => (a[0] + a[1]).localeCompare(b[0] + b[1]));

const L = [];
L.push('-- =============================================================================');
L.push('-- JFRESH OS · Backend step 1 · Access reference data');
L.push('-- GENERATED by tools/export-access-seed.js from the JS access engines.');
L.push('-- Do not edit by hand: change the engines, re-run the tool, commit a new migration.');
L.push(`-- ${X.PLANTS.length} plants · ${roleKeys.length} roles · ${permList.length} permissions · ${uniq.length} grants`);
L.push('-- =============================================================================');
L.push('');
L.push('insert into public.plants (id, name, short_name) values');
L.push(X.PLANTS.map(p => `  (${q(p.id)}, ${q(name(p.n)[0])}, ${q(p.short)})`).join(',\n'));
L.push('on conflict (id) do update set name = excluded.name, short_name = excluded.short_name;');
L.push('');
L.push('insert into public.roles (key, name_id, name_en, experience, role_group, landing_screen, landing_code) values');
L.push(roleKeys.map(k => { const r = X.ROLES[k], n = name(r.n); return `  (${q(k)}, ${q(n[0])}, ${q(n[1])}, ${q(r.exp)}, ${q(r.group)}, ${q(r.landing)}, ${q(r.land)})`; }).join(',\n'));
L.push('on conflict (key) do update set name_id = excluded.name_id, name_en = excluded.name_en, experience = excluded.experience,');
L.push('  role_group = excluded.role_group, landing_screen = excluded.landing_screen, landing_code = excluded.landing_code;');
L.push('');
L.push('insert into public.permissions (key) values');
L.push(permList.map(p => `  (${q(p)})`).join(',\n'));
L.push('on conflict (key) do nothing;');
L.push('');
L.push('insert into public.role_permissions (role_key, permission_key) values');
L.push(uniq.map(g => `  (${q(g[0])}, ${q(g[1])})`).join(',\n'));
L.push('on conflict do nothing;');
L.push('');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, L.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), out)}: ${X.PLANTS.length} plants, ${roleKeys.length} roles, ${permList.length} permissions, ${uniq.length} grants`);
