\set ON_ERROR_STOP 1
begin;

insert into auth.users (id, email) values
  ('00000000-0000-0000-0000-000000000001', 'owner@test.local'),
  ('00000000-0000-0000-0000-000000000002', 'admin@test.local'),
  ('00000000-0000-0000-0000-000000000003', 'hr@test.local'),
  ('00000000-0000-0000-0000-000000000004', 'operator@test.local'),
  ('00000000-0000-0000-0000-000000000005', 'newstaff@test.local');
select public.bootstrap_owner('owner@test.local');
insert into public.user_roles (user_id, role_key, is_default) values
  ('00000000-0000-0000-0000-000000000002', 'sysadmin', true),
  ('00000000-0000-0000-0000-000000000003', 'hr', true),
  ('00000000-0000-0000-0000-000000000004', 'operator', true);
insert into public.user_plants values ('00000000-0000-0000-0000-000000000004', 'PL-01');

create function pg_temp.as_user(n int) returns void language sql as $$
  select set_config('request.jwt.claim.sub', '00000000-0000-0000-0000-00000000000' || n, true);
$$;
create function pg_temp.ok(c boolean, msg text) returns void language plpgsql as $$
begin if not coalesce(c, false) then raise exception 'FAIL: %', msg; end if; raise notice 'PASS: %', msg; end $$;
create function pg_temp.fails(sql text, msg text) returns void language plpgsql as $$
begin
  begin execute sql; exception when others then raise notice 'PASS: % (%)', msg, sqlerrm; return; end;
  raise exception 'FAIL: % (statement succeeded)', msg;
end $$;

set local role authenticated;

-- HR registers a new employee (id generated by the database).
select pg_temp.as_user(3);
insert into public.employees (full_name, job_title, department, plant_id, email)
values ('Wayan Baru', 'Operator', 'Operasional', 'PL-01', 'newstaff@test.local');
select pg_temp.ok((select id like 'EMP-%' from public.employees where full_name = 'Wayan Baru'), 'employee id generated');
select pg_temp.ok((select account_id is null from public.employees_overview() where full_name = 'Wayan Baru'), 'HR sees the employee waiting for access');
select pg_temp.ok((select created_by = '00000000-0000-0000-0000-000000000003' from public.employees where full_name = 'Wayan Baru'), 'created_by recorded');
update public.employees set phone = '0812' where full_name = 'Wayan Baru';
select pg_temp.ok((select phone = '0812' from public.employees where full_name = 'Wayan Baru'), 'HR updates the employee');
select pg_temp.ok((select count(*) = 0 from public.profiles where id <> auth.uid()), 'HR does not read other accounts');
select pg_temp.fails($$insert into public.user_roles (user_id, role_key, is_default) values ('00000000-0000-0000-0000-000000000004', 'qc', false)$$, 'HR cannot grant roles');
delete from public.employees where full_name = 'Wayan Baru';
select pg_temp.ok((select count(*) = 1 from public.employees where full_name = 'Wayan Baru'), 'HR cannot delete employees (row stays)');

-- An operator sees nothing of it.
select pg_temp.as_user(4);
select pg_temp.ok((select count(*) = 0 from public.employees_overview()), 'operator gets an empty overview');
select pg_temp.fails($$insert into public.employees (full_name) values ('X')$$, 'operator cannot register employees');

-- The admin links the account (the Edge Function creates the Auth user) and ticks two roles.
select pg_temp.as_user(2);
update public.profiles set employee_id = (select id from public.employees where full_name = 'Wayan Baru'), display_name = 'Wayan Baru', can_switch_role = true
 where id = '00000000-0000-0000-0000-000000000005';
insert into public.user_roles (user_id, role_key, is_default) values
  ('00000000-0000-0000-0000-000000000005', 'operator', true), ('00000000-0000-0000-0000-000000000005', 'qc', false);
insert into public.user_plants values ('00000000-0000-0000-0000-000000000005', 'PL-01');
select pg_temp.ok((select account_id is not null and roles = array['operator','qc'] from public.employees_overview() where full_name = 'Wayan Baru'), 'overview shows account and both roles');
select pg_temp.fails($$insert into public.user_roles (user_id, role_key, is_default) values ('00000000-0000-0000-0000-000000000005', 'owner', false)$$, 'system admin cannot grant owner');
select pg_temp.fails($$update public.profiles set all_plants = true where id = '00000000-0000-0000-0000-000000000005'$$, 'system admin cannot grant all plants');
-- Untick qc.
delete from public.user_roles where user_id = '00000000-0000-0000-0000-000000000005' and role_key = 'qc';
select pg_temp.ok((select roles = array['operator'] from public.employees_overview() where full_name = 'Wayan Baru'), 'role removed');

-- The new staff member signs in.
select pg_temp.as_user(5);
select pg_temp.ok((select (a ->> 'email') = 'newstaff@test.local' and (a ->> 'department') = 'Operasional' and (a ->> 'all_plants') = 'false'
                     and jsonb_array_length(a -> 'roles') = 1 and (a -> 'permissions') ? 'ops.receive' from (select public.my_access() a) x), 'my_access has email, department, roles, permissions');

reset role;
rollback;
